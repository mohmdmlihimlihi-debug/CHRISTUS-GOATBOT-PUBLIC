const message = `النص الذي أرسلته...`;

module.exports = {
  config: {
    name: "swww",
    version: "1.2.0",
    author: "shtot",
    countDown: 3,
    role: 1,
    shortDescription: "إرسال دوري",
    category: "tools"
  },

  onStart: async function ({ api, event, args }) {

    // إيقاف
    if (args[0] === "stop") {
      const timer = running.get(TARGET_THREAD_ID);

      if (!timer) {
        return api.sendMessage("❌ ما كاين حتى إرسال شغال.", event.threadID);
      }

      clearInterval(timer);
      running.delete(TARGET_THREAD_ID);

      return api.sendMessage("✅ توقف الإرسال.", event.threadID);
    }

    // منع تشغيل أكثر من عملية
    if (running.has(TARGET_THREAD_ID)) {
      return api.sendMessage(
        "⚠️ الإرسال شغال بالفعل.\nاستعمل: swww stop",
        event.threadID
      );
    }

    api.sendMessage(
      "✅ بدأ الإرسال.\n⏱️ كل 40 ثانية\n🛑 للإيقاف: swww stop",
      event.threadID
    );

    const timer = setInterval(() => {
      api.sendMessage(message, TARGET_THREAD_ID, (err) => {
        if (err) {
          console.error("خطأ في الإرسال:", err);
        }
      });
    }, 40000); // 40 ثانية

    running.set(TARGET_THREAD_ID, timer);
  }
};
